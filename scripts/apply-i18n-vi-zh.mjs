function buildDict(map) {
  const out = {};
  for (const [key, val] of Object.entries(en)) {
    out[key] = map[val] ?? val;
  }
  return out;
}

function writeDictFile(name, dict) {
  const lines = ['import type { TranslationDict } from "./ko";', "", `export const ${name}: TranslationDict = {`];
  for (const [key, val] of Object.entries(dict)) {
    const escaped = String(val).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
    lines.push(`  "${key}": "${escaped}",`);
  }
  lines.push("};", "");
  fs.writeFileSync(path.join(__dirname, `../src/lib/i18n/${name}.ts`), lines.join("\n"));
}

